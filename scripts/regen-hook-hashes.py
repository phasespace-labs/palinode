#!/usr/bin/env python3
"""Regenerate ``palinode/hooks/shipped-hashes.json`` from this repo's history.

The manifest records every hook script content palinode has shipped, so that
(ADR-023 §2-3):

* a test can fail when a script changes while its ``# palinode-hook-version:``
  stamp still names a version a release shipped with other content, and
* ``palinode hooks update`` can tell a pristine copy of an older release
  (safe to refresh) from a copy someone edited.

Every historical copy of each script is read: the string constants in
``palinode/cli/init.py`` (where the scripts lived until ADR-023), the copies in
``examples/hooks/``, and the package files under ``palinode/hooks/scripts/``,
plus the working tree, so a script changed but not yet committed is recorded
too. Each distinct content is one entry: its sha256, its stamp (``null`` when
unstamped), and the first release tag whose tree shipped it (``null`` when no
release has).

    uv run python scripts/regen-hook-hashes.py                    # rewrite the manifest
    uv run python scripts/regen-hook-hashes.py --output /tmp/x.json

**Entries already in the manifest are never dropped.** A shallow clone, or the
squashed public repo, knows fewer revisions than the development repo, and a
regeneration that pruned to what it could see would make those installs look
edited. The output is a union, so running the script on its own output
changes nothing.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from palinode.hooks import MANIFEST_NAME, SCRIPT_NAMES, hook_version  # noqa: E402

MANIFEST = Path("palinode") / "hooks" / MANIFEST_NAME
PACKAGE_DIR = "palinode/hooks/scripts"
EXAMPLES_DIR = "examples/hooks"
INIT_PY = "palinode/cli/init.py"

#: The ``cli/init.py`` constant that held each script before ADR-023.
INIT_CONSTANTS = {
    "HOOK_SCRIPT": "palinode-session-end.sh",
    "SESSION_START_HOOK_SCRIPT": "palinode-session-start.sh",
    "USER_PROMPT_SUBMIT_HOOK_SCRIPT": "palinode-user-prompt-submit.sh",
    "POST_COMPACT_HOOK_SCRIPT": "palinode-post-compact.sh",
    "CURSOR_HOOK_SCRIPT": "palinode-cursor-hook.sh",
    "ANTIGRAVITY_HOOK_SCRIPT": "palinode-agy-hook.sh",
}

RELEASE_TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")
SCHEMA = 1
NOTE = (
    "Every hook script content palinode has shipped, per script, newest first: its "
    "sha256, its palinode-hook-version stamp (null when unstamped) and the first "
    "release that shipped it (null when none has). Generated by "
    "scripts/regen-hook-hashes.py from git history; run it after changing a hook "
    "script rather than editing this file by hand. Entries are never dropped."
)


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=REPO_ROOT, check=True, capture_output=True, text=True,
    ).stdout


def _show(rev: str, path: str) -> str | None:
    result = subprocess.run(
        ["git", "show", f"{rev}:{path}"], cwd=REPO_ROOT, capture_output=True, text=True,
    )
    return result.stdout if result.returncode == 0 else None


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _init_constants(source: str) -> dict[str, str]:
    """Script contents held as plain string constants in one revision of init.py."""
    found: dict[str, str] = {}
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return found
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if (
            isinstance(target, ast.Name)
            and target.id in INIT_CONSTANTS
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            found[INIT_CONSTANTS[target.id]] = node.value.value
    return found


def _contents_at(rev: str) -> dict[str, set[str]]:
    """Every copy of each script in one revision's tree."""
    out: dict[str, set[str]] = {name: set() for name in SCRIPT_NAMES}
    init = _show(rev, INIT_PY)
    if init:
        for name, text in _init_constants(init).items():
            out[name].add(text)
    for directory in (EXAMPLES_DIR, PACKAGE_DIR):
        for name in SCRIPT_NAMES:
            text = _show(rev, f"{directory}/{name}")
            if text is not None:
                out[name].add(text)
    return out


def _releases() -> list[tuple[str, str]]:
    """``(tag, version)`` for every release tag, oldest first."""
    tags = []
    for tag in _git("tag").split():
        match = RELEASE_TAG.match(tag)
        if match:
            tags.append((tuple(int(g) for g in match.groups()), tag))
    return [(tag, tag[1:]) for _, tag in sorted(tags)]


def _history() -> list[str]:
    """Commits that touched any script source, oldest first."""
    paths = [INIT_PY, EXAMPLES_DIR, PACKAGE_DIR]
    return _git("log", "--reverse", "--format=%H", "--", *paths).split()


def generate(existing: dict | None) -> dict:
    # sha -> entry, per script; insertion order = first appearance, oldest first.
    scripts: dict[str, dict[str, dict]] = {name: {} for name in SCRIPT_NAMES}

    def record(name: str, text: str) -> None:
        sha = _sha(text)
        if sha not in scripts[name]:
            scripts[name][sha] = {"sha256": sha, "version": hook_version(text), "released": None}

    for rev in _history():
        for name, texts in _contents_at(rev).items():
            for text in sorted(texts):
                record(name, text)
    for name in SCRIPT_NAMES:
        path = REPO_ROOT / PACKAGE_DIR / name
        if path.is_file():
            record(name, path.read_text(encoding="utf-8"))

    for tag, version in _releases():
        for name, texts in _contents_at(tag).items():
            for text in texts:
                entry = scripts[name].get(_sha(text))
                if entry is not None and entry["released"] is None:
                    entry["released"] = version

    # Union with what the manifest already records. Every recorded entry is
    # kept, in its recorded order, with a release this history cannot see; a
    # content the manifest lacks goes first (newest). The order therefore does
    # not depend on how much history this clone has.
    previous = (existing or {}).get("scripts", {})
    merged: dict[str, list[dict]] = {}
    for name in SCRIPT_NAMES:
        found = scripts[name]
        kept: list[dict] = []
        for old in previous.get(name, []):
            entry = dict(old)
            seen = found.get(entry["sha256"])
            if seen is not None and entry.get("released") is None:
                entry["released"] = seen["released"]
            kept.append(entry)
        recorded = {e["sha256"] for e in kept}
        new = [e for e in reversed(list(found.values())) if e["sha256"] not in recorded]
        merged[name] = new + kept
    return {"schema": SCHEMA, "_note": NOTE, "scripts": merged}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=REPO_ROOT / MANIFEST)
    args = parser.parse_args()
    existing = None
    if args.output.is_file():
        existing = json.loads(args.output.read_text(encoding="utf-8"))
    elif (REPO_ROOT / MANIFEST).is_file():
        existing = json.loads((REPO_ROOT / MANIFEST).read_text(encoding="utf-8"))
    manifest = generate(existing)
    args.output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
